-- -----------------------------------------------------------------------------
-- 1. Logged sets — one row per set
-- -----------------------------------------------------------------------------
create table if not exists public.sets (
  id          text primary key,                         -- generated by the app
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  session_id  text not null,                            -- one workout = one session
  logged_at   timestamptz not null default now(),
  date        date not null,                            -- local calendar day of the workout
  workout     text not null,                            -- "Upper A", "Lower B", ...
  exercise    text not null,
  set_number  smallint not null check (set_number > 0),
  weight_lb   numeric(6,2) check (weight_lb >= 0),
  reps        smallint check (reps >= 0),
  created_at  timestamptz not null default now()
);
create index if not exists sets_user_time_idx     on public.sets (user_id, logged_at);
create index if not exists sets_user_exercise_idx on public.sets (user_id, exercise, date);

-- -----------------------------------------------------------------------------
-- 2. Bodyweight — one row per weigh-in (the app keeps one per day)
-- -----------------------------------------------------------------------------
create table if not exists public.bodyweight (
  id          text primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  logged_at   timestamptz not null default now(),
  date        date not null,
  weight_lb   numeric(5,1) not null check (weight_lb > 0),
  created_at  timestamptz not null default now()
);
create index if not exists bodyweight_user_date_idx on public.bodyweight (user_id, date);

-- -----------------------------------------------------------------------------
-- 3. Workout plan — one row per user, the whole plan as JSON
--    Created from the app (Dashboard → "Save plan to database"),
--    then edit it in Table Editor → user_plan → plan.
-- -----------------------------------------------------------------------------
create table if not exists public.user_plan (
  user_id     uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  plan        jsonb not null check (jsonb_typeof(plan) = 'array'),
  updated_at  timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- 4. Row Level Security — every user can only see and change their own rows
-- -----------------------------------------------------------------------------
alter table public.sets       enable row level security;
alter table public.bodyweight enable row level security;
alter table public.user_plan  enable row level security;

do $$
declare t text;
begin
  foreach t in array array['sets', 'bodyweight', 'user_plan'] loop
    execute format('drop policy if exists "own rows - select" on public.%I', t);
    execute format('drop policy if exists "own rows - insert" on public.%I', t);
    execute format('drop policy if exists "own rows - update" on public.%I', t);
    execute format('drop policy if exists "own rows - delete" on public.%I', t);

    execute format('create policy "own rows - select" on public.%I for select to authenticated using ((select auth.uid()) = user_id)', t);
    execute format('create policy "own rows - insert" on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)', t);
    execute format('create policy "own rows - update" on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)', t);
    execute format('create policy "own rows - delete" on public.%I for delete to authenticated using ((select auth.uid()) = user_id)', t);
  end loop;
end $$;

-- Logged-out visitors get nothing
revoke all on public.sets, public.bodyweight, public.user_plan from anon;
grant select, insert, update, delete on public.sets, public.bodyweight, public.user_plan to authenticated;

-- -----------------------------------------------------------------------------
-- 5. Handy views for looking at your data in Supabase (the app doesn't need them)
--    security_invoker = the view follows the same "own rows only" rules.
-- -----------------------------------------------------------------------------

-- Best set ever per exercise (ranked by estimated 1-rep max)
create or replace view public.exercise_bests with (security_invoker = true) as
select distinct on (user_id, exercise)
  user_id, exercise, weight_lb, reps, date,
  round(weight_lb * (1 + reps / 30.0), 1) as est_1rm_lb
from public.sets
where weight_lb is not null and reps is not null
order by user_id, exercise, weight_lb * (1 + reps / 30.0) desc, date desc;

-- Top set per exercise per workout day — chart this to see progress
create or replace view public.exercise_progress with (security_invoker = true) as
select distinct on (user_id, exercise, session_id)
  user_id, exercise, date, workout, weight_lb, reps,
  round(weight_lb * (1 + reps / 30.0), 1) as est_1rm_lb
from public.sets
where weight_lb is not null and reps is not null
order by user_id, exercise, session_id, weight_lb * (1 + reps / 30.0) desc;

-- Weekly totals (weeks start Monday)
create or replace view public.weekly_summary with (security_invoker = true) as
select
  user_id,
  date_trunc('week', date)::date                         as week_start,
  count(distinct session_id)                             as workouts,
  count(*)                                               as sets,
  round(sum(coalesce(weight_lb, 0) * coalesce(reps, 0))) as volume_lb
from public.sets
group by user_id, date_trunc('week', date)
order by week_start desc;

revoke all on public.exercise_bests, public.exercise_progress, public.weekly_summary from anon;
grant select on public.exercise_bests, public.exercise_progress, public.weekly_summary to authenticated;
